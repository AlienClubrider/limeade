// deploy/local-models.yaml: the local models LiteLLM serves, written by the hub from what each machine has
// installed and pulled into deploy/litellm.yaml by its `include`. JSON under a comment line, which YAML reads
// as-is. LiteLLM only reads its config at start, so a change means a restart (systemd user unit).

import { execFile } from 'node:child_process'
import { readFile, rename, writeFile } from 'node:fs/promises'
import { promisify } from 'node:util'
import type { LiteLlmEntry } from '../domain/local-models.ts'
import type { LiteLlmModelsFile } from '../ports.ts'

const MARK = '# Generated by agent-hub from each machine\'s installed models. Edit deploy/local-models.json, not this.'

export class LiteLlmModelsYaml implements LiteLlmModelsFile {
  private o: { file: string; url: string; unit?: string; fetch?: typeof fetch; run?: (cmd: string, args: string[]) => Promise<unknown>; readyTimeoutMs?: number }
  constructor(o: LiteLlmModelsYaml['o']) {
    this.o = o
  }

  /** null until the hub has written it (the unit starts LiteLLM with an empty list if it's missing). */
  async read(): Promise<LiteLlmEntry[] | null> {
    try {
      const text = await readFile(this.o.file, 'utf8')
      if (!text.startsWith(MARK)) return null
      const list = JSON.parse(text.slice(MARK.length))?.model_list
      return Array.isArray(list) ? list : null
    } catch {
      return null
    }
  }

  async write(entries: readonly LiteLlmEntry[]): Promise<void> {
    const tmp = `${this.o.file}.tmp`
    await writeFile(tmp, `${MARK}\n${JSON.stringify({ model_list: entries }, null, 1)}\n`, { mode: 0o600 })
    await rename(tmp, this.o.file)
  }

  async restart(): Promise<void> {
    const run = this.o.run ?? ((cmd, args) => promisify(execFile)(cmd, args, { timeout: 60_000 }))
    await run('systemctl', ['--user', 'restart', this.o.unit ?? 'litellm.service'])
    const f = this.o.fetch ?? fetch
    const until = Date.now() + (this.o.readyTimeoutMs ?? 90_000)
    while (Date.now() < until) {
      const ok = await f(`${this.o.url}/health/liveliness`, { signal: AbortSignal.timeout(2000) }).then((r) => r.ok, () => false)
      if (ok) return
      await new Promise((r) => setTimeout(r, 500))
    }
    throw new Error("LiteLLM didn't come back after the restart")
  }
}
